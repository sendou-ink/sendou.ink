/**
 * Rolls random weapons for the two sides of a lobby game, balanced with what SendouQ results say about them.
 *
 * How it works:
 *
 * 1. {@link WeaponRollOptions.candidates} times, 8 weapons of different base weapons are drawn, each as likely as
 *    its SendouQ usage share raised to {@link WeaponRollOptions.popularityExponent}, less likely if the lobby rolled
 *    it in one of its last sets (see {@link repeatFactor}).
 * 2. Every 4v4 split of the 8 is scored with a cost, the sum of the weighted cost terms below, and the
 *    cheapest split is that candidate's.
 * 3. The cheapest candidate wins, more candidates trade variety for balance. Every weight 0 is a plain random roll.
 *
 * Cost terms:
 *
 * 1. {@link strengthCost}: how far the win probability predicted from the weapons alone is from 50%
 * 2. {@link shapeCost}: how rare each team's frontline/midline/backline counts are in real SendouQ teams
 * 3. {@link shapeMismatchCost}: how differently shaped the two teams are
 * 4. {@link specialStackCost}: weapons of a team sharing a special
 *
 * The weapon data is generated by `scripts/compute-weapon-roll-data.ts`, its top comment explains the model.
 */

import * as R from "remeda";
import { mainWeaponParams } from "~/features/build-analyzer/core/utils";
import * as WeaponRange from "~/features/comp-analyzer/core/WeaponRange";
import type {
	MainWeaponId,
	ModeShort,
	SpecialWeaponId,
} from "~/modules/in-game-lists/types";
import {
	mainWeaponIds,
	type weaponCategories,
	weaponIdToBaseWeaponId,
	weaponIdToCategory,
	weaponIdToType,
} from "~/modules/in-game-lists/weapon-ids";
import {
	type LobbyRolledWeapons,
	type LobbyWeaponRandomizer,
	PLAYERS_PER_SET,
	PLAYERS_PER_TEAM,
} from "../lobbies-constants";
import { BACKLINE_MIN_RANGE } from "./PlayerRoles";
import rawWeaponRollData from "./weapon-roll-data.json";

export interface WeaponRollOptions {
	/** Mode of the game, picks the mode specific weapon strengths. `null` uses the all modes ones. */
	mode: ModeShort | null;
	/** Draws of 8 weapons tried, the cheapest wins */
	candidates: number;
	/** 0 = every weapon equally likely, 1 = as likely as in SendouQ */
	popularityExponent: number;
	/** Per percentage point the weapons' predicted win probability is off 50% */
	strengthWeight: number;
	/** Per unit of {@link shapeCost} */
	shapeWeight: number;
	/** Per player of {@link shapeMismatchCost} */
	shapeMismatchWeight: number;
	/** Per weapon of {@link specialStackCost} */
	specialStackWeight: number;
	/** How likely a weapon rolled in the previous set is drawn compared to normally, 1 = no penalty, 0 = never */
	repeatWeight: number;
	/** Over how many sets the repeat penalty fades away */
	repeatFadeSets: number;
}

// tweak these on the /lobbies/weapon-roll-test page
export const DEFAULT_WEAPON_ROLL_OPTIONS: WeaponRollOptions = {
	mode: null,
	candidates: 20,
	popularityExponent: 0.4,
	strengthWeight: 0.7,
	shapeWeight: 0.8,
	shapeMismatchWeight: 0.9,
	specialStackWeight: 1.2,
	repeatWeight: 0.25,
	repeatFadeSets: 3,
};

/** Options each weapon randomizer of a lobby rolls with, chaotic being a plain roll of any weapon. */
const RANDOMIZER_OPTIONS: Record<
	Exclude<LobbyWeaponRandomizer, "OFF">,
	WeaponRollOptions
> = {
	CHAOTIC: {
		mode: null,
		candidates: 1,
		popularityExponent: 0,
		strengthWeight: 0,
		shapeWeight: 0,
		shapeMismatchWeight: 0,
		specialStackWeight: 0,
		repeatWeight: DEFAULT_WEAPON_ROLL_OPTIONS.repeatWeight,
		repeatFadeSets: DEFAULT_WEAPON_ROLL_OPTIONS.repeatFadeSets,
	},
	BALANCED: DEFAULT_WEAPON_ROLL_OPTIONS,
};

export const WEAPON_TIERS = ["FRONTLINE", "MIDLINE", "BACKLINE"] as const;
export type WeaponTier = (typeof WEAPON_TIERS)[number];

/** Range below which a weapon counts as frontline. Splattershot (11.9) is below, Splat Brella (11.0) too. */
const FRONTLINE_MAX_RANGE = 12.5;

/** Categories whose tier is fixed, their simulated range (e.g. a roller's flick) not saying where they play. */
const CATEGORY_TIERS: Partial<
	Record<(typeof weaponCategories)[number]["name"], WeaponTier>
> = {
	ROLLERS: "FRONTLINE",
	BRUSHES: "FRONTLINE",
	SPLATANAS: "FRONTLINE",
	CHARGERS: "BACKLINE",
};

/** Weapons whose tier is set by hand, keyed by base weapon id so the alt kits follow. Wins over {@link CATEGORY_TIERS}. */
const WEAPON_TIERS_BY_HAND: Partial<Record<MainWeaponId, WeaponTier>> = {
	// Explosher
	3040: "BACKLINE",
	// Heavy Splatling
	4010: "BACKLINE",
	// Heavy Edit Splatling
	4050: "BACKLINE",
};

/** Share given to a team shape never seen in the data, so its cost stays finite. */
const UNSEEN_SHAPE_SHARE = 0.0005;

/** Generated weapon data, see `scripts/compute-weapon-roll-data.ts`. */
export interface WeaponRollData {
	generatedAt: string;
	mapCount: number;
	/** Keyed by weapon id, alt skins folded to their base */
	weapons: Record<string, WeaponRollDataWeapon>;
	/** Share of real SendouQ teams per {@link shapeKey} */
	shapes: Record<string, number>;
}

interface WeaponRollDataWeapon {
	/** Share of the reported weapons */
	usage: number;
	/** Win log-odds a team gets from having this weapon instead of an average one */
	strength: number;
	/** Standard error of `strength` */
	strengthSe: number;
	byMode: Partial<Record<ModeShort, { strength: number; strengthSe: number }>>;
}

// TODO: consider fitting the strengths from scanner ingested matches too (full 4v4 weapons, no partial reports) once there are enough of them
export const WEAPON_ROLL_DATA: WeaponRollData = rawWeaponRollData;

const MOST_COMMON_SHAPE_SHARE = Math.max(
	UNSEEN_SHAPE_SHARE,
	...Object.values(WEAPON_ROLL_DATA.shapes),
);

/** Weapons that can be rolled: every weapon with its own kit, alt skins left out. */
export const ROLLABLE_WEAPON_IDS = mainWeaponIds.filter(
	(weaponId) => weaponIdToType(weaponId) !== "ALT_SKIN",
);

export interface WeaponRollCost {
	strength: number;
	shape: number;
	shapeMismatch: number;
	specialStack: number;
	total: number;
}

export interface WeaponRollResult {
	alpha: MainWeaponId[];
	bravo: MainWeaponId[];
	/** Alpha's win probability predicted from the weapons alone */
	alphaWinProbability: number;
	cost: WeaponRollCost;
}

/**
 * Rolls the weapons of both sides, see the top of the file. `recentRolls` are the weapons of the lobby's previous
 * sets, newest first. `random` is injectable for tests.
 */
export function roll(
	options: WeaponRollOptions,
	{
		recentRolls = [],
		random = Math.random,
	}: { recentRolls?: MainWeaponId[][]; random?: () => number } = {},
): WeaponRollResult {
	const repeatFactors = new Map<MainWeaponId, number>();
	for (const [i, weapons] of recentRolls.entries()) {
		const factor = repeatFactor(options, i + 1);
		for (const baseId of weapons.map(weaponIdToBaseWeaponId)) {
			repeatFactors.set(
				baseId,
				Math.min(factor, repeatFactors.get(baseId) ?? 1),
			);
		}
	}

	const drawWeights = ROLLABLE_WEAPON_IDS.map(
		(weaponId) =>
			usageOf(weaponId) ** options.popularityExponent *
			(repeatFactors.get(weaponIdToBaseWeaponId(weaponId)) ?? 1),
	);

	let best: WeaponRollResult | null = null;
	for (let i = 0; i < Math.max(1, options.candidates); i++) {
		const weapons = drawWeighted(drawWeights, random);

		for (const split of allSplits(weapons)) {
			const result = evaluate(split, options);
			if (!best || result.cost.total < best.cost.total) best = result;
		}
	}

	return best!;
}

/** Rolls the weapons each side of a set gets with the lobby's randomizer, `recentRolls` being its previous sets' newest first. */
export function rollForSet(
	randomizer: Exclude<LobbyWeaponRandomizer, "OFF">,
	recentRolls: LobbyRolledWeapons[] = [],
): LobbyRolledWeapons {
	const rolled = roll(RANDOMIZER_OPTIONS[randomizer], {
		recentRolls: recentRolls.map((weapons) => [
			...weapons.ALPHA,
			...weapons.BRAVO,
		]),
	});

	return { ALPHA: rolled.alpha, BRAVO: rolled.bravo };
}

/**
 * Multiplier of the draw weight of a weapon rolled `setsAgo` sets ago: {@link WeaponRollOptions.repeatWeight} for
 * the previous set, fading linearly back to 1 over {@link WeaponRollOptions.repeatFadeSets} sets.
 */
export function repeatFactor(
	{
		repeatWeight,
		repeatFadeSets,
	}: Pick<WeaponRollOptions, "repeatWeight" | "repeatFadeSets">,
	setsAgo: number,
) {
	if (setsAgo > repeatFadeSets) return 1;

	return (
		1 - ((1 - repeatWeight) * (repeatFadeSets - setsAgo + 1)) / repeatFadeSets
	);
}

/** Scores the given teams with the cost terms, see the top of the file. */
export function evaluate(
	{ alpha, bravo }: { alpha: MainWeaponId[]; bravo: MainWeaponId[] },
	options: WeaponRollOptions,
): WeaponRollResult {
	const alphaWinProbability = winProbability(alpha, bravo, options.mode);

	const strength =
		options.strengthWeight * strengthCost(alphaWinProbability) * 100;
	const shape = options.shapeWeight * (shapeCost(alpha) + shapeCost(bravo));
	const shapeMismatch =
		options.shapeMismatchWeight * shapeMismatchCost(alpha, bravo);
	const specialStack =
		options.specialStackWeight *
		(specialStackCost(alpha) + specialStackCost(bravo));

	return {
		alpha,
		bravo,
		alphaWinProbability,
		cost: {
			strength,
			shape,
			shapeMismatch,
			specialStack,
			total: strength + shape + shapeMismatch + specialStack,
		},
	};
}

/** Alpha's win probability predicted from the weapons' strengths alone. */
export function winProbability(
	alpha: MainWeaponId[],
	bravo: MainWeaponId[],
	mode: ModeShort | null,
) {
	const teamStrength = (team: MainWeaponId[]) =>
		R.sumBy(team, (weaponId) => strengthOf(weaponId, mode).strength);

	return 1 / (1 + Math.exp(teamStrength(bravo) - teamStrength(alpha)));
}

/** How many players of one team would need to change tier for the teams to be shaped the same. */
export function shapeMismatchCost(
	alpha: MainWeaponId[],
	bravo: MainWeaponId[],
) {
	const alphaCounts = tierCounts(alpha);
	const bravoCounts = tierCounts(bravo);

	return (
		R.sumBy(WEAPON_TIERS, (tier) =>
			Math.abs(alphaCounts[tier] - bravoCounts[tier]),
		) / 2
	);
}

/** Weapons of the team whose special another weapon of the team already has. */
export function specialStackCost(team: MainWeaponId[]) {
	return team.length - new Set(team.map(specialOf)).size;
}

/** Share of real SendouQ teams with the shape, see {@link shapeKey}. */
export function shapeShare(key: string) {
	return WEAPON_ROLL_DATA.shapes[key] ?? UNSEEN_SHAPE_SHARE;
}

/** Frontline, midline and backline counts of a team, e.g. "2-1-1". */
export function shapeKey(team: MainWeaponId[]) {
	const counts = tierCounts(team);

	return WEAPON_TIERS.map((tier) => counts[tier]).join("-");
}

const tierCache = new Map<MainWeaponId, WeaponTier>();
/** Where on the map the weapon plays, from its category or else its range. */
export function tierOf(weaponId: MainWeaponId): WeaponTier {
	const cached = tierCache.get(weaponId);
	if (cached) return cached;

	const range = rangeOf(weaponId);
	const tier =
		WEAPON_TIERS_BY_HAND[weaponIdToBaseWeaponId(weaponId)] ??
		CATEGORY_TIERS[weaponIdToCategory(weaponId)] ??
		(range >= BACKLINE_MIN_RANGE
			? "BACKLINE"
			: range < FRONTLINE_MAX_RANGE
				? "FRONTLINE"
				: "MIDLINE");

	tierCache.set(weaponId, tier);

	return tier;
}

const rangeCache = new Map<MainWeaponId, number>();
/** Simulated range of the weapon, see `WeaponRange`. */
export function rangeOf(weaponId: MainWeaponId) {
	const cached = rangeCache.get(weaponId);
	if (cached !== undefined) return cached;

	const range = WeaponRange.ofMainWeapon(weaponId).range;
	rangeCache.set(weaponId, range);

	return range;
}

/** Strength of the weapon in the mode, the all modes one if the mode has no data. 0 for weapons without data. */
export function strengthOf(weaponId: MainWeaponId, mode: ModeShort | null) {
	const weapon = WEAPON_ROLL_DATA.weapons[weaponId];
	if (!weapon) return { strength: 0, strengthSe: 0 };

	return (mode ? weapon.byMode[mode] : undefined) ?? weapon;
}

/** Share of the SendouQ reported weapons that are this weapon. */
export function usageOf(weaponId: MainWeaponId) {
	return WEAPON_ROLL_DATA.weapons[weaponId]?.usage ?? 0;
}

const specialCache = new Map<MainWeaponId, SpecialWeaponId>();
/** Special of the weapon's kit. */
export function specialOf(weaponId: MainWeaponId): SpecialWeaponId {
	const cached = specialCache.get(weaponId);
	if (cached !== undefined) return cached;

	const special = mainWeaponParams(weaponId).specialWeaponId;
	specialCache.set(weaponId, special);

	return special;
}

/** Distance (0-0.5) of a win probability from an even 50%. */
function strengthCost(alphaWinProbability: number) {
	return Math.abs(alphaWinProbability - 0.5);
}

/** How much rarer the team's shape is than the most common one in real teams, in log units (0 = most common). */
function shapeCost(team: MainWeaponId[]) {
	return Math.log(MOST_COMMON_SHAPE_SHARE / shapeShare(shapeKey(team)));
}

function tierCounts(team: MainWeaponId[]) {
	const counts: Record<WeaponTier, number> = {
		FRONTLINE: 0,
		MIDLINE: 0,
		BACKLINE: 0,
	};
	for (const weaponId of team) counts[tierOf(weaponId)]++;

	return counts;
}

/**
 * Draws 8 of the rollable weapons by weight without replacement (Efraimidis-Spirakis, in log space), at most one per
 * base weapon so e.g. Splattershot and Tentatek aren't both drawn. A weight of 0 is never drawn.
 */
function drawWeighted(weights: number[], random: () => number) {
	const keyed = ROLLABLE_WEAPON_IDS.map((weaponId, i) => ({
		weaponId,
		key:
			weights[i] > 0
				? Math.log(random()) / weights[i]
				: Number.NEGATIVE_INFINITY,
	})).sort((a, b) => b.key - a.key);

	const drawn: MainWeaponId[] = [];
	const drawnBaseIds = new Set<MainWeaponId>();
	for (const { weaponId } of keyed) {
		const baseId = weaponIdToBaseWeaponId(weaponId);
		if (drawnBaseIds.has(baseId)) continue;

		drawn.push(weaponId);
		drawnBaseIds.add(baseId);
		if (drawn.length === PLAYERS_PER_SET) break;
	}

	return drawn;
}

/** Every way to split 8 weapons into two teams of 4, the first always on alpha so mirrors aren't repeated. */
function allSplits(weapons: MainWeaponId[]) {
	const [first, ...rest] = weapons;
	const result: Array<{ alpha: MainWeaponId[]; bravo: MainWeaponId[] }> = [];

	const choose = (startIdx: number, picked: MainWeaponId[]) => {
		if (picked.length === PLAYERS_PER_TEAM - 1) {
			const alpha = [first, ...picked];
			result.push({
				alpha,
				bravo: weapons.filter((weaponId) => !alpha.includes(weaponId)),
			});
			return;
		}

		for (let i = startIdx; i < rest.length; i++) {
			choose(i + 1, [...picked, rest[i]]);
		}
	};

	choose(0, []);

	return result;
}
