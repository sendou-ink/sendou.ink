const NAME_MAX_LENGTH = 10;

const INVISIBLE_CHARACTER_REGEXP = /^(?:\p{Cf}|\p{Variation_Selector})$/u;

export async function up(db: Kysely<any>): Promise<void> {
	const rows = await db
		.selectFrom("User")
		.select([sql<number>`rowid`.as("rowId"), "inGameName"])
		.where("inGameName", "is not", null)
		.execute();

	for (const row of rows) {
		const replaced = withoutOverflowingTrailingSpaces(
			[...row.inGameName]
				.filter((character) => !INVISIBLE_CHARACTER_REGEXP.test(character))
				.map((character) => REPLACEMENTS.get(character) ?? character)
				.join(""),
		);
		if (replaced === row.inGameName) continue;

		await db
			.updateTable("User")
			.set({ inGameName: replaced })
			.where(sql`rowid`, "=", row.rowId)
			.execute();
	}
}

function withoutOverflowingTrailingSpaces(inGameName: string) {
	const discriminatorIndex = inGameName.lastIndexOf("#");
	if (discriminatorIndex === -1) return inGameName;

	const name = inGameName.slice(0, discriminatorIndex);
	if ([...name].length <= NAME_MAX_LENGTH) return inGameName;

	return `${name.trimEnd()}${inGameName.slice(discriminatorIndex)}`;
}
